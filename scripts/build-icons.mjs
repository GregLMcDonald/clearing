// Regenerates js/icons.js from the Material Icons (Round) SVG set.
// The app never loads an icon font or hits a CDN: only the glyphs listed here
// are inlined. Add a name (see https://fonts.google.com/icons) and re-run:
//   npm run icons
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const STYLE = "round";
const NAMES = [
  "air", "arrow_back", "auto_awesome", "calendar_month", "check", "check_circle", "close",
  "cloud_download", "cloud_off", "cloud_sync", "delete_outline", "error_outline",
  "expand_more", "file_download", "file_upload", "graphic_eq", "history", "info",
  "language", "menu_book", "music_note", "pause", "play_arrow", "record_voice_over",
  "refresh", "save", "search", "self_improvement", "skip_next", "skip_previous", "spa",
  "swap_horiz", "timer", "tune",
];

const out = {};
for (const name of NAMES) {
  const file = path.join(ROOT, "node_modules/@material-design-icons/svg", STYLE, `${name}.svg`);
  const svg = await readFile(file, "utf8");
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  out[name] = inner;
}

const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");
const src = `// GENERATED by scripts/build-icons.mjs — do not edit by hand.
// Material Icons (${STYLE}), Apache License 2.0, https://github.com/google/material-design-icons
export const ICONS = {
${body}
};
`;
await writeFile(path.join(ROOT, "js/icons.js"), src);
console.log(`Wrote js/icons.js (${NAMES.length} icons)`);
